import type { IncomingMessage, ServerResponse } from 'node:http';
import { uuidv7 } from '@etkinlik/shared';
import type { Params } from 'nestjs-pino';
import type { Env } from '../config/env.js';

export const REQUEST_ID_HEADER = 'X-Request-Id';

/**
 * KVKK: personal data must never reach the logs in clear text. Request bodies
 * are not logged at all; these paths catch structured fields that do appear.
 */
export const REDACT_PATHS = [
  'req.headers.cookie',
  'req.headers.authorization',
  'res.headers["set-cookie"]',
  '*.studentNumber',
  '*.phone',
  '*.phoneNumber',
  '*.latitude',
  '*.longitude',
  '*.coordinates',
  '*.lat',
  '*.lng',
  '*.token',
  '*.password',
  '*.secret',
];

/**
 * Request ids are always generated by the server; a client-supplied
 * X-Request-Id is ignored so callers cannot forge or collide log correlation.
 * assignRequestId runs as the very first middleware (before body parsing), so
 * even requests rejected by the body parser carry an id.
 */
export function assignRequestId(req: IncomingMessage, res: ServerResponse): string {
  const id = uuidv7();
  req.id = id;
  res.setHeader(REQUEST_ID_HEADER, id);
  return id;
}

/** pino-http hook: reuse the id assigned by assignRequestId. */
export function resolveRequestId(req: IncomingMessage, res: ServerResponse): string {
  return typeof req.id === 'string' ? req.id : assignRequestId(req, res);
}

export function loggerParams(env: Env, options: { http: boolean }): Params {
  return {
    pinoHttp: {
      level: env.LOG_LEVEL,
      redact: { paths: REDACT_PATHS, censor: '[MASKED]' },
      genReqId: resolveRequestId,
      autoLogging: options.http
        ? { ignore: (req) => req.url?.endsWith('/health/live') ?? false }
        : false,
      customProps: () => ({ service: options.http ? 'api' : 'worker' }),
      serializers: {
        req: (req: { id: unknown; method: unknown; url: unknown }) => ({
          id: req.id,
          method: req.method,
          url: req.url,
        }),
      },
    },
  };
}

/** The server-generated request id (see assignRequestId). */
export function requestIdOf(req: IncomingMessage): string {
  return typeof req.id === 'string' ? req.id : 'unknown';
}
